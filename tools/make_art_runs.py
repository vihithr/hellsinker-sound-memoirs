"""Trace the original title once. Its geometry is identical in every palette."""
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
im = Image.open(root / "assets/memoirs-title.bmp").convert("RGB")
def pigment(pixel):
    for i, color in enumerate(((223, 108, 70), (204, 204, 204))):
        if sum((a-b)**2 for a, b in zip(pixel, color)) < 500:
            return i
    return None

runs = []
for y in range(im.height):
    row = [pigment(im.getpixel((x, y))) for x in range(im.width)]
    x = 0
    while x < im.width:
        start, color = x, row[x]
        x += 1
        while x < im.width and row[x] == color:
            x += 1
        if color is not None:
            runs.append("{%d,%d,%d,%d}" % (start, y, x-start, color))
(root / "src/themed_art_runs.h").write_text(
    "// Generated by tools/make_art_runs.py\n#pragma once\n"
    "struct ArtRun { short x, y, w; unsigned char c; };\n"
    "static const ArtRun kTitleRuns[] = {\n" + ",".join(runs) +
    "\n};\nconstexpr int kTitleRunsN = sizeof(kTitleRuns) / sizeof(kTitleRuns[0]);\n")
