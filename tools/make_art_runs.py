"""Emit run-length vector tables for the title / frequency-axis artwork so the
runtime DRAWS them as crisp scaled rects (true vector, any resolution) instead
of blitting a blurry bitmap crop.  Coords are in 2x source pixels; runtime
halves them to logical.  Output: src/themed_art_runs.h
"""
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(ROOT, "assets")

def dist(a, b): return sum((a[i] - b[i]) ** 2 for i in range(3))
def nearest(c, srcs):
    bi, bd = 0, dist(c, srcs[0])
    for i, s in enumerate(srcs[1:], 1):
        d = dist(c, s)
        if d < bd: bd, bi = d, i
    return bi

THEMES = [
    dict(title=(232,63,8),   titleBlock=(205,205,205), frame=(132,230,224), axisLabel=(232,120,40), panel=(216,220,208)),
    dict(title=(255,120,60), titleBlock=(40,44,52),    frame=(60,220,210),  axisLabel=(255,170,60), panel=(24,28,34)),
    dict(title=(255,60,180), titleBlock=(24,28,44),    frame=(0,255,220),   axisLabel=(0,230,255),  panel=(14,18,30)),
    dict(title=(170,60,30),  titleBlock=(222,216,202), frame=(90,110,100),  axisLabel=(150,90,40),  panel=(238,232,218)),
]
TITLE_SRC = [(223,108,70), (204,204,204), (217,226,224)]   # red, gray block, outer bg(skip)
AXIS_SRC  = [(132,230,224), (232,120,40), (216,220,208)]  # cyan, orange, panel bg(skip)

def runs_for(im, srcs, keep):
    px = im.load(); w, h = im.size
    runs = []
    for y in range(h):
        x = 0
        while x < w:
            ci = nearest(px[x, y], srcs)
            if ci not in keep:
                x += 1; continue
            x0 = x
            while x < w and nearest(px[x, y], srcs) == ci:
                x += 1
            runs.append((x0, y, x - x0, ci))
    return runs

lines = ["// auto-generated by tools/make_art_runs.py -- do not edit",
         "#pragma once",
         "struct ArtRun { short x, y, w; unsigned char c; };"]
for i, th in enumerate(THEMES):
    t = Image.open(os.path.join(A, "memoirs-title.bmp")).convert("RGB")
    px = t.load(); w, h = t.size
    # core-only: keep strong red / strong gray, DROP antialiased halo (halo
    # kept as solid made the traced title bolder than the original).
    for y in range(h):
        for x in range(w):
            c = px[x, y]
            if dist(c, (223,108,70)) < 500: px[x, y] = th['title']
            elif dist(c, (204,204,204)) < 500: px[x, y] = th['titleBlock']
            else: px[x, y] = (1, 2, 3)
    tr = runs_for(t, [th['title'], th['titleBlock'], (1, 2, 3)], keep={0, 1})
    lines.append(f"static const ArtRun kTitleRuns{i}[] = {{")
    lines.append(",".join(f"{{{x},{y},{w},{c}}}" for x, y, w, c in tr))
    lines.append("};")
    lines.append(f"static const int kTitleRuns{i}N = {len(tr)};")

    a = Image.open(os.path.join(A, "memoirs-axis.bmp")).convert("RGB")
    px = a.load(); w, h = a.size
    tgt = [th['frame'], th['axisLabel'], None]
    cls = [[nearest(px[x, y], AXIS_SRC) for x in range(w)] for y in range(h)]
    # dilate the orange label mask by 1 source px so traced strokes reach the
    # original's solid chunky weight (raw trace was sub-pixel thin / hollow).
    dil = [[cls[y][x] for x in range(w)] for y in range(h)]
    for y in range(h):
        for x in range(w):
            if cls[y][x] == 1:
                for dy in (-1, 0, 1):
                    for dx in (-1, 0, 1):
                        ny, nx = y + dy, x + dx
                        if 0 <= ny < h and 0 <= nx < w and dil[ny][nx] != 0:
                            dil[ny][nx] = 1
    for y in range(h):
        for x in range(w):
            ci = dil[y][x]
            px[x, y] = tgt[ci] if tgt[ci] else (1, 2, 3)
    ar = runs_for(a, [th['frame'], th['axisLabel'], (1, 2, 3)], keep={0, 1})
    lines.append(f"static const ArtRun kAxisRuns{i}[] = {{")
    lines.append(",".join(f"{{{x},{y},{w},{c}}}" for x, y, w, c in ar))
    lines.append("};")
    lines.append(f"static const int kAxisRuns{i}N = {len(ar)};")
    print(f"theme {i}: title runs={len(tr)} axis runs={len(ar)}")

lines.append("static const ArtRun* kTitleRuns[kThemeCount] = { kTitleRuns0, kTitleRuns1, kTitleRuns2, kTitleRuns3 };")
lines.append("static const int kTitleRunsN[kThemeCount] = { kTitleRuns0N, kTitleRuns1N, kTitleRuns2N, kTitleRuns3N };")
lines.append("static const ArtRun* kAxisRuns[kThemeCount] = { kAxisRuns0, kAxisRuns1, kAxisRuns2, kAxisRuns3 };")
lines.append("static const int kAxisRunsN[kThemeCount] = { kAxisRuns0N, kAxisRuns1N, kAxisRuns2N, kAxisRuns3N };")
open(os.path.join(ROOT, "src", "themed_art_runs.h"), "w").write("\n".join(lines) + "\n")
print("wrote src/themed_art_runs.h")